"""Text preparation preserves the reviewed corpus and exact token budget without local ML inference or SQLite."""

import argparse
import asyncio
import builtins
import hashlib
from pathlib import Path
from typing import Any

import pytest

from nimbus.park_ingest import load_catalog, load_prepared
from nimbus.park_text import record_hash, to_embedding_text
from tools.build_park_index import DATA_DIR, Manifest, PreparationTokenizer, prepare_chunks, read_chunks, run


def test_tokenizer_only_preparation_preserves_the_reviewed_forty_passages(monkeypatch: pytest.MonkeyPatch) -> None:
    """This digest was captured from the approved pre-migration corpus, not generated by the new writer."""
    original_import = builtins.__import__

    def guarded_import(name: str, *args: Any, **kwargs: Any) -> Any:
        """Fail immediately if text preparation tries to import a local embedding model or weight downloader."""
        assert name.split(".")[0] not in {"torch", "transformers", "sentence_transformers", "huggingface_hub"}
        return original_import(name, *args, **kwargs)

    monkeypatch.setattr(builtins, "__import__", guarded_import)
    manifest = Manifest.model_validate_json((DATA_DIR / "manifest.json").read_text(encoding="utf-8"))
    counter = PreparationTokenizer()
    chunks = prepare_chunks(read_chunks(manifest, DATA_DIR / "snapshots"), counter)
    assert len(chunks) == 40
    fingerprint = hashlib.sha256(
        "\n".join(record_hash(item) for item in sorted(chunks, key=lambda item: item.id)).encode()
    ).hexdigest()
    assert fingerprint == "fd20bc53043e440ade786c74a38203bee8f9a7a95b9002c92cb170845122ddd8"
    assert max(counter.token_count(to_embedding_text(item.title, item.section, item.text)) for item in chunks) == 252
    assert all("embedding" not in item.model_dump() for item in chunks)


def test_bundled_tokenizer_must_match_its_pinned_digest(tmp_path: Path) -> None:
    """Changed tokenizer rules cannot silently produce a differently truncated hosted index."""
    path = tmp_path / "tokenizer.json"
    path.write_text("{}", encoding="utf-8")
    with pytest.raises(ValueError, match="reviewed revision"):
        PreparationTokenizer(path)


def test_builder_prepares_matching_artifacts_without_network_or_vectors(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    """A normal build reads reviewed snapshots only; the separate publisher owns all provider calls."""

    def no_network(*args: object, **kwargs: object) -> None:
        """Creating an HTTP client during a normal preparation run is a regression."""
        pytest.fail("Preparation attempted network access")

    monkeypatch.setattr("tools.build_park_index.httpx2.AsyncClient", no_network)
    target, catalog = tmp_path / "prepared.json", tmp_path / "catalog.json"
    arguments = argparse.Namespace(
        manifest=DATA_DIR / "manifest.json", output=target, catalog=catalog, refresh=False, publish=False
    )
    assert asyncio.run(run(arguments)) == 0
    prepared, compact = load_prepared(target), load_catalog(catalog)
    assert prepared["index_version"] == compact["index_version"]
    assert prepared["source_count"] == compact["source_count"] == 13
    assert prepared["chunk_count"] == compact["chunk_count"] == 40
    assert all("text" in item for item in prepared["chunks"])
    assert all("text" not in item and "embedding" not in item for item in compact["chunks"])
    assert "no embeddings" in capsys.readouterr().out
